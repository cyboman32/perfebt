<#
.SYNOPSIS
  Builds PerfeBT, packs it as dist/PerfeBT_<Tag>.zip and publishes it as a GitHub release.

.DESCRIPTION
  The build needs the game's and ModTek's assemblies, which cannot be published, so releases are built on a machine
  with the game installed instead of in GitHub Actions.

  Steps: check that the working tree is clean; build Release with the version taken from the tag; pack PerfeBT.dll,
  mod.json (its "Version" set to the tag's version) and README.md into a PerfeBT/ folder inside the zip, so it can be
  extracted straight into BATTLETECH/Mods; create and push the tag at HEAD if it does not exist yet; create the
  GitHub release with the zip attached. Release notes come from the CHANGELOG section of that version, or are
  generated by GitHub when there is none.

  Everything is written under dist/, which git ignores.

.PARAMETER Tag
  Release tag, e.g. v0.9.1 or 0.9.1. A leading "v" is dropped for the version number.

.PARAMETER GameDir
  BATTLETECH install folder. Defaults to the GameDir in PerfeBT.csproj.

.PARAMETER DryRun
  Build and pack only: no tag, no push, no release.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts/release.ps1 -Tag v0.9.1
#>
param(
    [Parameter(Mandatory = $true)][string]$Tag,
    [string]$GameDir,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Invoke-Checked([string]$exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe $($arguments -join ' ') failed with exit code $LASTEXITCODE" }
}

$version = $Tag -replace '^v', ''
if ($version -notmatch '^\d+(\.\d+){1,3}([-+][0-9A-Za-z.-]+)?$') { throw "Tag '$Tag' is not a version (expected e.g. v0.9.1)" }
$numericVersion = ($version -split '[-+]')[0]

$gh = (Get-Command gh -ErrorAction SilentlyContinue).Source
if (-not $gh) { $gh = Join-Path $env:ProgramFiles 'GitHub CLI\gh.exe' }
if (-not (Test-Path $gh)) { throw 'GitHub CLI (gh) not found' }

# A release must be reproducible from its tag, so it is built only from committed sources.
$dirty = git status --porcelain
if ($dirty -and -not $DryRun) { throw "Working tree has uncommitted changes:`n$($dirty -join "`n")" }
if ($dirty) { Write-Warning 'Dry run with uncommitted changes: the package is not what the tag would contain.' }

$head = git rev-parse HEAD
if (git rev-parse -q --verify "refs/tags/$Tag" 2>$null) {
    $tagCommit = git rev-list -n 1 $Tag
    if ($tagCommit -ne $head) { throw "Tag $Tag points to $tagCommit, not HEAD ($head). Check out the tag or pick a new one." }
}

# Build
$buildArgs = @('build', 'PerfeBT.csproj', '-c', 'Release', '-nologo', '-v', 'q',
    "-p:Version=$numericVersion", "-p:InformationalVersion=$version")
if ($GameDir) { $buildArgs += "-p:GameDir=$GameDir" }
Invoke-Checked 'dotnet' $buildArgs
$dll = Join-Path $root 'bin\Release\PerfeBT.dll'
if (-not (Test-Path $dll)) { throw "Build output not found: $dll" }

# Pack
$dist = Join-Path $root 'dist'
$stage = Join-Path $dist "PerfeBT_$Tag"
$modDir = Join-Path $stage 'PerfeBT'
$zip = Join-Path $dist "PerfeBT_$Tag.zip"
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
if (Test-Path $zip) { Remove-Item $zip -Force }
New-Item -ItemType Directory -Path $modDir -Force | Out-Null

Copy-Item $dll $modDir
Copy-Item (Join-Path $root 'README.md') $modDir
$utf8 = New-Object System.Text.UTF8Encoding($false)
$modJson = [System.IO.File]::ReadAllText((Join-Path $root 'mod.json'), $utf8)
$versionPattern = New-Object System.Text.RegularExpressions.Regex('"Version"\s*:\s*"[^"]*"')
if (-not $versionPattern.IsMatch($modJson)) { throw 'mod.json has no "Version" field' }
$modJson = $versionPattern.Replace($modJson, "`"Version`": `"$version`"", 1)
[System.IO.File]::WriteAllText((Join-Path $modDir 'mod.json'), $modJson, $utf8)

Compress-Archive -Path $modDir -DestinationPath $zip
Write-Host "Packed $zip"
Get-ChildItem $modDir | ForEach-Object { Write-Host "  PerfeBT/$($_.Name)  $($_.Length) bytes" }

# Release notes: the CHANGELOG section of this version, if any.
$notesFile = Join-Path $dist "PerfeBT_$Tag.notes.md"
$changelog = [System.IO.File]::ReadAllLines((Join-Path $root 'CHANGELOG.md'), $utf8)
$notes = New-Object System.Collections.Generic.List[string]
$inSection = $false
foreach ($line in $changelog) {
    if ($line -match '^## ') {
        if ($inSection) { break }
        $inSection = ($line.Substring(3).Trim() -eq $version)
        continue
    }
    if ($inSection) { $notes.Add($line) }
}
$hasNotes = ($notes | Where-Object { $_.Trim() }).Count -gt 0
if ($hasNotes) {
    [System.IO.File]::WriteAllText($notesFile, ($notes -join "`n").Trim() + "`n", $utf8)
    Write-Host "Release notes from CHANGELOG section $version"
} else {
    Write-Host "No CHANGELOG section '## $version'; GitHub will generate the notes"
}

if ($DryRun) {
    Write-Host 'Dry run: no tag, push or release.'
    return
}

if (-not (git rev-parse -q --verify "refs/tags/$Tag" 2>$null)) {
    Invoke-Checked 'git' @('tag', '-a', $Tag, '-m', "PerfeBT $version")
}
Invoke-Checked 'git' @('push', 'origin', "refs/tags/$Tag")

$releaseArgs = @('release', 'create', $Tag, $zip, '--title', "PerfeBT $version", '--verify-tag')
if ($hasNotes) { $releaseArgs += @('--notes-file', $notesFile) } else { $releaseArgs += '--generate-notes' }
Invoke-Checked $gh $releaseArgs
Write-Host "Released $Tag"
